// Settings verification uses isolated browser storage and fictional demo accounts.
const { chromium } = require('../../next/node_modules/playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
 let scenarios = 0;
 for (const {viewport,theme} of [{viewport:{width:1280,height:900},theme:'dark'},{viewport:{width:480,height:520},theme:'light'}]) {
  const page = await browser.newPage({ viewport, reducedMotion: 'reduce' });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.addInitScript(theme => localStorage.setItem('multi-codex-theme', theme), theme);
  await page.clock.setFixedTime(new Date('2026-10-31T12:00:00Z'));
  await page.goto(`${process.env.SETTINGS_BASE_URL || 'http://127.0.0.1:1420'}/?demo=1`);
  const open = async label => { await page.getByRole('button',{name:'Settings',exact:true}).click(); await page.getByRole('button',{name:label}).click(); };
  const footer = async () => { const b = await page.getByRole('button',{name:'Save settings',exact:true}).boundingBox(); assert(b.y >= 0 && b.y+b.height <= viewport.height, 'Save button is clipped'); };
  await open(/Refresh.*Usage/);
  assert.equal(await page.getByRole('combobox').inputValue(), '10');
  await page.getByRole('combobox').selectOption('1'); await footer();
  await page.getByRole('button',{name:'Save settings',exact:true}).click();
  await page.reload(); await open(/Refresh.*Usage/);
  assert.equal(await page.getByRole('combobox').inputValue(), '1');
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await open(/Notifications.*Account alerts/);
  await page.getByRole('checkbox',{name:'Below 30%',exact:true}).check();
  await page.getByRole('checkbox',{name:'Notifications for Personal',exact:true}).uncheck();
  await page.getByRole('checkbox',{name:/Weekly usage reset/}).uncheck();
  await page.getByRole('checkbox',{name:/Sign-in expired/}).uncheck();
  await page.getByRole('button',{name:'Send test notification'}).scrollIntoViewIfNeeded(); await footer();
  assert(await page.getByRole('button',{name:'Send test notification'}).isDisabled());
  await page.getByRole('button',{name:'Save settings',exact:true}).click();
  await open(/Notifications.*Account alerts/);
  assert(await page.getByRole('checkbox',{name:'Below 30%',exact:true}).isChecked());
  assert(!await page.getByRole('checkbox',{name:'Notifications for Personal',exact:true}).isChecked());
  assert(!await page.getByRole('checkbox',{name:/Weekly usage reset/}).isChecked());
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await open(/Launch settings/);
  assert.equal(await page.getByRole('checkbox',{name:/Enable Orbit/}).count(),0);
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await open(/Orbit.*Companions/);
  assert.equal(await page.getByRole('combobox',{name:/costume|festival/i}).count(),0);
  assert.equal(await page.locator('.avatar-template-preview canvas').count(),6);
  assert.equal(await page.locator('.avatar-template-preview .seasonal-costume').count(),6);
  await page.getByRole('checkbox',{name:'Festival clothing',exact:true}).uncheck();
  await page.getByRole('checkbox',{name:'Play a soft sound for new reminders'}).scrollIntoViewIfNeeded(); await footer();
  const bounds = await page.getByRole('checkbox',{name:'Play a soft sound for new reminders'}).boundingBox();
  const actions = await page.locator('.orbit-settings-dialog .dialog-actions').boundingBox();
  assert(bounds.y+bounds.height < actions.y, 'Orbit fields overlap the footer');
  await page.getByRole('button',{name:'Save settings',exact:true}).click();
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('multi-codex-preferences:v1')));
  assert.equal(saved.refreshMinutes,1); assert.equal(saved.seasonalAvatars,false); assert(saved.mutedAccounts.includes('demo-personal'));
  await page.reload(); await open(/Orbit.*Companions/);
  assert.equal(await page.locator('.seasonal-costume').count(),0);
  assert(!await page.getByRole('checkbox',{name:'Festival clothing',exact:true}).isChecked());
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  await open(/Notifications.*Account alerts/);
  assert(!await page.getByRole('checkbox',{name:/Sign-in expired/}).isChecked());
  assert.equal(await page.getByText(/Twitter|Tibo|calendar/i).count(),0);
  assert.equal(errors.length,0,errors.join('\n'));
  await page.close(); scenarios++;
 }
 await browser.close(); console.log(JSON.stringify({status:'passed',scenarios,refreshPersistence:true,accountPreferences:true,orbitOnly:true,costumeOptOut:true,reachableFooters:true,noPageErrors:true}));
})().catch(error => { console.error(error); process.exit(1); });
